"""Regenerate reads.js: the globals and arrays each <Type>AddToArray reads.

Source: the event-sheet dump of 278 LOADING EDITOR. The queue stores exactly
these values per batch variant, so replaying them through the game's own
AddToArray writes the same device row. Own parts the same way: MyCPU_*AddToArray (103 CPU LOADING) and
MyGPU_AddToArray (138 GPU LOADING), read from the same dump folder.
Run after a game update:
  python3 gen_reads.py ../../game-files/dump/"278 LOADING EDITOR.txt"
"""
import json
import re
import sys
from pathlib import Path

TYPES = {'Smartphone': 'SMARTPHONE', 'Tablet': 'TABLET', 'Laptop': 'LAPTOP', 'Watches': 'WATCHES',
         'Headphones': 'HEADPHONES', 'TV': 'TV', 'Scooter': 'SCOOTER', 'Keyboard': 'KEYBOARD',
         'Console': 'CONSOLE', 'VR': 'VR'}


PARTS = {'CPU': '103 CPU LOADING.txt', 'GPU': '138 GPU LOADING.txt'}


def _funcs(src):
    for part in re.split(r'\n  FUNC \["', src)[1:]:
        yield part.split('"', 1)[0], part.split('\nGROUP', 1)[0]


def main(dump):
    src = Path(dump).read_text()
    out = {}
    for name, body in _funcs(src):
        key = TYPES.get(name[:-len('AddToArray')]) if name.endswith('AddToArray') else None
        if not key:
            continue
        target = sorted(set(re.findall(r'→ (Array\w+) Arr\.Acts', body)))
        out[key] = {
            'target': target[0],
            'vars': sorted(set(re.findall(r'\$(\w+)', body))),
            'arrays': sorted(set(re.findall(r'@(Array\w+)', body)) - set(target)),
        }
    parts = {}
    for key, sheet in PARTS.items():
        names = set()
        for name, body in _funcs((Path(dump).parent / sheet).read_text()):
            if name.endswith('AddToArray'):
                names |= set(re.findall(r'\$(\w+)', body))
        parts[key] = sorted(names - {'DeviceTypeCreatingNow', 'class', 'OfficeType'})
    js = ('// Generated by gen_reads.py from 278 LOADING EDITOR: what each AddToArray reads.\n'
          'var _DTQ_READS = ' + json.dumps(out, separators=(',', ':')) + ';\n'
          '// Own parts: what MyCPU_*AddToArray (103) and MyGPU_AddToArray (138) read.\n'
          'var _DTQ_PART_READS = ' + json.dumps(parts, separators=(',', ':')) + ';\n')
    (Path(__file__).resolve().parent / 'reads.js').write_text(js)
    print('reads.js:', {k: len(v['vars']) for k, v in out.items()}, {k: len(v) for k, v in parts.items()})


if __name__ == '__main__':
    main(sys.argv[1])
